/**
 * Prints the reference draft fixture or the document tables (issue #122).
 *
 * Run from the repo root:
 * `pnpm --filter @tafsila/api exec tsx ../test-fixtures/src/gen-reference-drafts.ts ts > packages/test-fixtures/src/reference-drafts.ts`
 * and with `md` instead of `ts` to print the tables for docs/engine/drafting-method.md.
 */
import type { Measurements } from "@tafsila/schemas";
import { egyptianSizeChart } from "./egyptian-size-chart";
import { REFERENCE_BLOCKS, REFERENCE_SIZES, type ReferenceSize } from "./reference-drafts-sizes";
import { computeReferenceDraft, type DraftResult } from "./reference-drafts-calc";

/**
 * Computes the draft of every reference size.
 *
 * @returns The draft result per size label.
 */
export function allDrafts(): Record<ReferenceSize, DraftResult> {
  return Object.fromEntries(
    REFERENCE_SIZES.map((s) => [s, computeReferenceDraft(egyptianSizeChart[s] as Measurements)]),
  ) as Record<ReferenceSize, DraftResult>;
}

/**
 * Renders the TypeScript source of `reference-drafts.ts`.
 *
 * @returns The file content (unformatted; run Prettier).
 */
export function renderFixtureSource(): string {
  const drafts = allDrafts();
  const sizes = REFERENCE_SIZES.map((s) => {
    const blocks = REFERENCE_BLOCKS.map((b) => `${b}: ${JSON.stringify(drafts[s][b])},`).join("\n");
    return `${s}: { ${blocks} },`;
  }).join("\n");
  return `/**
 * Reference drafts for the block issues of M2: key points (mm, x right, y down) of the bodice, straight skirt
 * and set-in sleeve for sizes S, M and XXL of \`egyptianSizeChart\`, drafted with the method of
 * docs/engine/drafting-method.md (ADR-122a). GENERATED by \`gen-reference-drafts.ts\`; do not edit by hand.
 * A test fails when this file differs from the calculation.
 */
import type { Point } from "@tafsila/schemas";
import type { ReferenceBlock, ReferenceSize } from "./reference-drafts-sizes";

/** Key points of one block, keyed by dotted name such as \`bodice.back.nape\`. */
export type ReferenceDraft = Readonly<Record<string, Point>>;

/** Reference key points per size and block. */
export const referenceDrafts: Readonly<Record<ReferenceSize, Readonly<Record<ReferenceBlock, ReferenceDraft>>>> = {
${sizes}
};
`;
}

/**
 * Formats a point as "x, y" for a table cell.
 *
 * @param point - The point.
 * @returns The text.
 */
function formatPoint(point: { x: number; y: number }): string {
  return `${point.x}, ${point.y}`;
}

/**
 * Renders one markdown table per block with a column per size.
 *
 * @returns The markdown tables.
 */
export function renderMarkdown(): string {
  const drafts = allDrafts();
  const out: string[] = [];
  for (const b of REFERENCE_BLOCKS) {
    const names = Object.keys(drafts.S[b]);
    out.push(`#### ${b}\n`, `| Key point | ${REFERENCE_SIZES.map((s) => s + " (x, y)").join(" | ")} |`);
    out.push(`| --- | ${REFERENCE_SIZES.map(() => "---").join(" | ")} |`);
    for (const n of names) {
      const cells = REFERENCE_SIZES.map((s) => formatPoint(drafts[s][b][n]!));
      out.push(`| \`${n}\` | ${cells.join(" | ")} |`);
    }
    out.push("");
  }
  out.push(
    "#### Derived lengths\n",
    `| Length | ${REFERENCE_SIZES.join(" | ")} |`,
    `| --- | ${REFERENCE_SIZES.map(() => "---").join(" | ")} |`,
  );
  for (const k of Object.keys(drafts.S.derived)) {
    const row = REFERENCE_SIZES.map((s) =>
      String((drafts[s].derived as unknown as Record<string, number>)[k]),
    );
    out.push(`| ${k} | ${row.join(" | ")} |`);
  }
  return out.join("\n");
}

if (process.argv[1]?.endsWith("gen-reference-drafts.ts")) {
  process.stdout.write(process.argv[2] === "md" ? renderMarkdown() : renderFixtureSource());
}
