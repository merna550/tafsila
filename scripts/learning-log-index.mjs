// pnpm learning-log:index: builds docs/handbook/learning-log.md from the files in docs/handbook/learning-log/.
// Option --check: exit 1 when the committed index is stale instead of writing it.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

export const LOG_DIR = "docs/handbook/learning-log";
export const INDEX_FILE = "docs/handbook/learning-log.md";

const HEADER = `<!-- GENERATED by \`pnpm learning-log:index\` from docs/handbook/learning-log/*.md. Do not edit by hand. -->

# Learning log

Dated list of concepts introduced by pull requests, newest first. Add one file per PR that teaches something new (a pattern, a tool, a technique) at \`docs/handbook/learning-log/<issue>-<slug>.md\`, then run \`pnpm learning-log:index\`.

| Date | PR / issue | Concept introduced | Read |
| ---- | ---------- | ------------------ | ---- |
`;

/**
 * Rewrites relative markdown link targets from entry-file perspective to index perspective (one `../` less).
 *
 * @param text - Markdown text written for a file inside `learning-log/`.
 * @returns The text with every relative link made relative to `docs/handbook/`.
 */
export function relinkForIndex(text) {
  return text.replace(/\]\((?!https?:|#|mailto:)\.\.\/([^)]*)\)/g, "]($1)");
}

/**
 * Reads one log entry file.
 *
 * @param path - Absolute path of the entry.
 * @returns The table cells of the entry plus its sort keys.
 */
function readEntry(path) {
  const text = readFileSync(path, "utf8").replaceAll("\r\n", "\n");
  const end = text.startsWith("---\n") ? text.indexOf("\n---", 4) : -1;
  const data = (end === -1 ? null : parseYaml(text.slice(4, end))) || {};
  const body = (end === -1 ? text : text.slice(end + 4)).trim();
  const [concept, ...rest] = body.split("\nRead:");
  const cell = (value) =>
    relinkForIndex(
      String(value ?? "")
        .split(/\s+/)
        .filter(Boolean)
        .join(" "),
    );
  return {
    date: String(data.date ?? ""),
    issue: String(data.issue ?? ""),
    concept: cell(concept),
    read: cell(rest.join(" ")),
  };
}

/**
 * Renders the index document from all entry files.
 *
 * @param root - Repo root.
 * @returns The full markdown text of `learning-log.md`.
 */
export function renderIndex(root) {
  const dir = join(root, LOG_DIR);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")) : [];
  const entries = files.map((name) => ({ name, ...readEntry(join(dir, name)) }));
  entries.sort((a, b) => b.date.localeCompare(a.date) || b.name.localeCompare(a.name));
  const rows = entries.map((e) => `| ${e.date} | ${e.issue} | ${e.concept} | ${e.read} |`);
  return `${HEADER}${rows.join("\n")}\n`;
}

/**
 * Reports whether the committed index matches the entry files.
 *
 * @param root - Repo root.
 * @returns An error message list (empty when the index is fresh).
 */
export function checkLearningLogIndex(root) {
  const file = join(root, INDEX_FILE);
  if (!existsSync(join(root, LOG_DIR))) return [];
  const current = existsSync(file) ? readFileSync(file, "utf8") : "";
  return current === renderIndex(root)
    ? []
    : [`Stale ${INDEX_FILE}: a learning-log file changed. Run: pnpm learning-log:index`];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const errors = checkLearningLogIndex(process.cwd());
    for (const message of errors) console.error(message);
    process.exit(errors.length > 0 ? 1 : 0);
  }
  writeFileSync(join(process.cwd(), INDEX_FILE), renderIndex(process.cwd()));
  console.log(`wrote ${INDEX_FILE}`);
}
